# range function = generate sequence of numbers
"""
Used mostly for 'for loops'.
"""
for number in range(5):
	print(number) # 0, 1, 2, 3, 4	(python starts for 0 not 1)


# usage
range(5) # 0, 1, 2, 3, 4

range(1, 6) # 1, 2, 3, 4, 5

"""
range(start, stop, step)
"""
range(2, 11, 2) # 2, 4, 6, 8, 10


# example
for number in range(1, 11):
	print(number)
