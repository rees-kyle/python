# comparison operators
"""
== 	Equal to
!= 	Not equal to
> 	Greater than
< 	Less than
>= 	Greater than or equal to
<=	Less than or equal 
"""


# examples
x = 10

print(x == 10) 	# true
print(x != 10)	# false
print(x > 5)	# true
print(x < 5)	# false
print(x >= 10)	# true
print(x <= 9)	# false


# with if
score = 75

if score >= 50:
	print("Pass")
else:
	print("Fail")


# == or =
x = 5		# assigns 5 to x
x == 5		# checks if x is equal to 5


