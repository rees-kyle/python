# arithmetic operators

# operators
a = 10
b = 3

print(a + b) # addition
print(a - b) # subtraction
print(a * b) # multiplication
print(a / b) # division
print(a // b) # floor division
print(a % b) # remainder
print(a ** b) # exponent


"""
order of operations:
1. parentheses = ()
2. exponents = **
3. multiplication/division = *, /, //, %
4. addition/subtraction = +, -
"""
result = 2 + 3 * 4
print(result) # 14

result = (2 + 3) * 4
print(result) # 20


# example
print(8 + 2) # 10
print(10 / 2) # 5
print(10 // 3) # 3
print(10 % 3) # 1
print(2 ** 4) # 16
