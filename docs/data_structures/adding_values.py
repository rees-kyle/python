# adding values = adding new items to collections

# lists
fruits = ["apple", "banana"]

fruits.append("orange")

print(fruits)

fruits.insert(1, "mango")	# insert at specific position

print(fruits)


# sets
numbers = {1, 2, 3}

numbers.add(4)

print(numbers)


# dictionaries
person = {
	"name": "Alex",
	"age": 25
}

person["city"] = "London"

print(person)

