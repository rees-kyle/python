# slicing = taking part of something
"""
Used for lists, tuples, strings or other sequences.

format:
sequence[start:stop]
"""

# examples
numbers = [10, 20, 30, 40, 50]

print(numbers[1:4])
print(numbers[0:3])
print(numbers[:3])
print(numbers[2:])
print(numbers[-2:])
print(numbers[::2])


word = "Python"
print(word[0:3])
